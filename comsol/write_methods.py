"""
Generate comsol/COMSOL_METHODS.md. Every number in the tables is read from the COMSOL exports
(comsol/data/raw.json, comsol/results.json, comsol/comparison.csv); nothing is typed in by hand.
Before the COMSOL run the tables show "pending".
"""
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import params as prm            # noqa: E402

RAW = os.path.join(HERE, "data", "raw.json")
CMP = os.path.join(HERE, "comparison.csv")
PENDING = "pending (run comsol/run_all.py)"

# physical explanations used when a quantity differs from the analytic model by more than 5 %
EXPLAIN = {
    "Rigid island": (
        "The analytic model applies a published 4.2 % strain ratio, which comes from strain-isolation "
        "designs loaded in stretching. In the COMSOL model the island sits in a bending laminate loaded by a "
        "constant bending moment (pure bending). The stiff region lowers the local curvature by roughly the "
        "ratio of bending stiffnesses, but it also moves the local neutral plane down into the island, "
        "which lengthens the lever arm to the channel. The two effects partly cancel. The result also "
        "depends on the unspecified PDMS thickness and island depth. On skin the patch is closer to "
        "curvature-controlled than moment-controlled, which would reduce the island benefit further."),
    "mitigation_pct_FS.Rigid island": None,
    "dyn_island": None,
    "zn_um": (
        "The analytic neutral plane weights each layer by E t (1D beam, uniaxial stress). The 2D model is "
        "plane strain, so each layer is weighted by E t/(1 - nu^2), and the Poisson ratios differ between layers "
        "(Au 0.44 vs PI 0.34). With nu = 0 the FE result reproduces the analytic value (see verification table)."),
    "eps_per_kappa_um": "see z_n: plane-strain vs uniaxial-stress layer weighting.",
    "check_debye_100mM_nm": (
        "The analytic value uses the empirical 0.304 nm/sqrt(I) rule; the FE value solves Poisson-Boltzmann with "
        "eps_r = 78.5 and T = 298.15 K."),
    "check_symmetric_stack_strain": (
        "Both values are numerically zero (the channel lies on the neutral plane to within the nanometre layers); "
        "relative differences between two near-zero numbers are not meaningful."),
}


def load():
    raw = json.load(open(RAW)) if os.path.exists(RAW) else None
    rows = list(csv.DictReader(open(CMP))) if os.path.exists(CMP) else []
    return raw, rows


def fmt(x, nd=4):
    if x is None:
        return PENDING
    try:
        return f"{float(x):.{nd}g}"
    except Exception:
        return str(x)


def main():
    raw, rows = load()
    mech = (raw or {}).get("mech", {})
    L = []
    w = L.append
    w("# COMSOL implementation: methods\n")
    w("_Generated by `comsol/write_methods.py` from the COMSOL exports. Do not edit the tables by hand._\n")
    ver = (raw or {}).get("comsol_version", PENDING)
    w(f"COMSOL Multiphysics version: {ver}. Models are built, meshed, solved and saved from Python "
      "(MPh + COMSOL Java API) by `comsol/build_model.py` and `comsol/run_all.py`. All inputs are COMSOL Parameters, "
      "defined in `comsol/params.py` (values imported from `motion_artifact_sim.PARAMS`).\n")

    # ------------------------------------------------------------------ model 1
    w("## 1. Laminate mechanics (`mos2_patch_mechanics.mph`)\n")
    w("**Interfaces.** Solid Mechanics (2D, plane strain, linear elastic, geometrically linear) for all layers thicker "
      "than 1 um (PI, PET, PMMA, PDMS, rigid island). The nanometre layers are not meshed as solids. The bonded Au (50 nm), "
      "MoS2 (0.65 nm) and Al2O3 (5 nm) films are plane-strain membranes on the device boundary, added as Weak "
      "Contributions to Solid Mechanics: -E t/(1-nu^2) (du/dx)_T test((du/dx)_T). This is the membrane (Layered Shell "
      "membrane-only) formulation. COMSOL 6.0 has no Membrane or Layered Shell interface for 2D planar components, so "
      "the membrane is written directly as a boundary weak form.\n")
    w("**MoS2 channel and van der Waals transfer.** The channel (length L_ch = "
      f"{prm.EXTRA['L_flake'][0]*1e6:g} um) carries its own axial displacement u_m on the boundary (Weak Form Boundary "
      "PDE) with membrane stiffness (E t)_MoS2 + (E t)_Al2O3. It is attached to the substrate surface at MoS2 mid-plane "
      "height, u_s = u - h_m dv/dx with h_m = t_Au + t_MoS2/2, through a tangential Thin Elastic Layer: "
      "-k_int (u_m - u_s) test(u_m - u_s). This is the Solid Mechanics Thin Elastic Layer equation (spring constant per "
      "unit area). It is written in weak form because the flake is a boundary, not a solid domain. With a free-ended flake the "
      "transferred strain follows shear-lag. eta is defined as the channel-averaged MoS2 strain divided by the strain "
      "of a perfectly bonded flake (pointwise constraint u_m = u_s), and k_int is calibrated by a secant iteration on "
      "COMSOL solves. Polymer and buried caps (eta = 1) use the pointwise constraint.\n")
    cal = mech.get("calib", {})
    w("| bonding case | target eta | calibrated k_int (N/m^3) | achieved eta |\n|---|---|---|---|")
    w(f"| bare MoS2 | {prm.P['eta_bare']} | {fmt(cal.get('k_bare'))} | {fmt(cal.get('eta_bare'), 5)} |")
    w(f"| 5 nm Al2O3 cap | {prm.P['eta_thinALD']} | {fmt(cal.get('k_ALD'))} | {fmt(cal.get('eta_ALD'), 5)} |")
    w(f"| polymer / buried cap | {prm.P['eta_polymer']} | pointwise constraint | 1 (exact) |\n")
    w("**Loading.** Pure bending: Rigid Connectors on both end faces with prescribed rotations +-kappa L/2, u_y = 0 on "
      "both ends and u_x = 0 on the left end only. The axial force is free, so N = 0 and the neutral plane is an "
      "outcome of the solve. Linear analysis at kappa_ref = 1 1/m, with an auxiliary sweep over the motion curvatures "
      "(1/25, 1/40, 1/300, 1/30 mm^-1). Outputs are read at x = 0, 5 mm from the loaded ends (Saint-Venant).\n")
    w("**Geometry variants.** Component `base`: substrate thickness and modulus are parameters (25 um PI baseline, 12.5 um "
      "PI, 2.5 um PET). Component `capped`: solid cap with thickness and modulus as parameters (1 um PMMA over 5 nm Al2O3; "
      f"buried PI/PI channel with a {prm.EXTRA['t_buried_cap'][0]*1e6:g} um top PI, giving about 1 um offset from the neutral "
      "plane; symmetric 25/25 um check). Component `island`: "
      f"{prm.EXTRA['w_isl'][0]*1e3:g} mm x {prm.EXTRA['t_isl'][0]*1e6:g} um island (E = 70 GPa) embedded flush in a "
      f"{prm.EXTRA['t_PDMS'][0]*1e6:g} um PDMS carrier (E = 2 MPa) under the 25 um PI device film. "
      "Prebent channel: no reasonable 2D geometry reproduces an out-of-plane prebuckled channel, so the published "
      f"strain ratio ({1e-3:g}) is applied to the COMSOL baseline.\n")
    w("**Materials beyond the Python model** (plane strain needs Poisson ratios; the 1D analytic model does not):\n")
    w("| parameter | value | source |\n|---|---|---|")
    for k, (v, u, src) in prm.EXTRA.items():
        w(f"| {k} | {v:g} {'' if u == '1' else u} | {src} |")
    w("")
    w("**Elements and mesh.** Mapped quadrilateral mesh, quadratic serendipity displacement elements (Solid Mechanics "
      "default), quadratic Lagrange elements for u_m. Horizontal element size is graded: 0.2 um/m within 2 um of the flake "
      "ends, 1 um/m on the flake and up to 20 um from it, 10 um/m to 200 um, 50 um/m to 1 mm and 150 um/m to the strip end "
      "(5 um/m near the island edges). Through the substrate there are 2m elements, where m = 2^(level-1).\n")
    w("**Mesh convergence** (baseline, kappa = 1 1/m; d% is relative to the finest level):\n")
    w("| level | elements | DOFs | eps/kappa spring (um) | d% | eps/kappa bonded (um) | d% | z_n (um) | solve time (s) |")
    w("|---|---|---|---|---|---|---|---|---|")
    for r in mech.get("convergence", []):
        w(f"| {r['level']} | {r['n_elem']} | {r['dofs']} | {r['epk_spring_um']:.5f} | {r['d_spring_pct']:.3f} | "
          f"{r['epk_tied_um']:.5f} | {r['d_tied_pct']:.3f} | {r['zn_um']:.4f} | {r['time_s']:.1f} |")
    if not mech.get("convergence"):
        w(f"| {PENDING} | | | | | | | | |")
    w(f"\nProduction mesh level: {mech.get('production_level', PENDING)} (the smallest level >= 3 whose eps/kappa is "
      "within 1 % of the finest level for both bonding models).\n")
    w("**Solver.** Stationary, linear, direct solver (COMSOL default for 2D, MUMPS/PARDISO), one auxiliary sweep "
      "per study over kappa. Studies `std_<component>_spring` (Thin Elastic Layer active, bonding constraint disabled) "
      "and `std_<component>_tied`.\n")
    nu0 = mech.get("nu0_check", {})
    w("**Verification against 1D laminate theory (all nu = 0, perfectly bonded):**\n")
    w("| quantity | COMSOL | analytic |\n|---|---|---|")
    w(f"| z_n (um) | {fmt(nu0.get('zn_m') and nu0['zn_m']*1e6, 6)} | 13.4326 |")
    w(f"| eps/kappa at MoS2 mid-plane, eta = 1 (um) | {fmt(nu0.get('epk_tied_m') and nu0['epk_tied_m']*1e6, 6)} | "
      f"{9.29418135371082/0.8:.4f} |\n")
    if mech:
        w(f"Rigid island: channel strain / baseline = {fmt(mech.get('island_ratio_to_baseline'))}; local curvature in the "
          f"island region / nominal curvature = {fmt(mech.get('island_local_kappa_ratio'))}. Buried channel z_n = "
          f"{fmt(mech.get('buried_zn_m', 0)*1e6)} um.\n")
    w("Strain-field images (COMSOL export, 600 dpi): `figures/comsol_strain_baseline_bent.png`, "
      "`figures/comsol_strain_rigid_island.png`, `figures/comsol_strain_buried_channel.png` (wrist curvature, R = 25 mm).\n")

    # ------------------------------------------------------------------ model 2
    w("## 2. Sensor chain (`mos2_sensor_chain.mph`)\n")
    w("**Coupling to mechanics.** The laminate is linear and quasi-static, so eps_ch(t) = (eps/kappa) kappa(t) exactly. "
      "Instead of 36 000 structural solves, eps/kappa is taken from model 1 (COMSOL value per structure, parameter `epk`), "
      "and the chain runs as global ODE/DAE equations. This is the fallback the method plan allows.\n")
    w("**Global ODE** (Global Equations interface): d theta/dt = k_on C_b(t) (1 - theta) - k_off theta, theta(0) = 0.\n")
    w("**Global variables (exact COMSOL expressions):**\n")
    w("| name | expression |\n|---|---|")
    for k, v in prm.chain_variables().items():
        w(f"| {k} | `{v}` |")
    w("")
    w("**Parameters:**\n")
    w("| name | expression |\n|---|---|")
    for k, v in prm.chain_params().items():
        w(f"| {k} | `{v}` |")
    w("")
    w("**Studies.** `std_stat`: stationary with an auxiliary sweep (four motions, seven structures, V_ov 0.05-1 V, "
      "r_c 0-0.8, mismatch 0-20 %, concentration and strain grids). `std_time`: 0-1800 s, output every 0.05 s "
      "(36 000 points), BDF with strict steps at output times, max step 0.05 s, rtol 1e-7. `std_motion`: 0-4 s waveforms.\n")
    w("**Post-processing** (`comsol/assemble.py`, on exported COMSOL time series): 2nd-order zero-phase Butterworth "
      "low-pass (scipy sosfiltfilt, f_c = 10 mHz, fs = 20 Hz), twin-sensor subtraction with 5 % gauge mismatch, inversion "
      "through the strain-free calibration curve, and per-block RMS and max error against the ideal motion-free reading. "
      "The filter-vs-frequency sweep (1 mHz-3 Hz) uses the COMSOL strain-to-current transfer curve (4001-point sweep, "
      "cubic interpolation).\n")

    # ------------------------------------------------------------------ model 3
    w("## 3. Debye length (`debye_1d.mph`)\n")
    dbe = (raw or {}).get("debye") or {}
    w("Electrostatics (AC/DC), 1D, 40 nm electrolyte, space charge rho = -2 F c sinh(V/V_th), eps_r = 78.5, T = 298.15 K, "
      "psi_0 = 1 mV (linear regime), 4000 elements. lambda_D = (integral of V dx)/psi_0, which is exact for the linear solution V = psi_0 exp(-x/lambda_D).\n")
    w("| ionic strength | COMSOL lambda_D (nm) | 0.304/sqrt(I) (nm) |\n|---|---|---|")
    w(f"| 50 mM | {fmt(dbe.get('lambda_50mM_nm'), 5)} | 1.3595 |")
    w(f"| 100 mM | {fmt(dbe.get('lambda_100mM_nm'), 5)} | 0.9613 |\n")

    # ------------------------------------------------------------------ run times
    w("## Run times\n")
    rt = (raw or {}).get("runtimes") or mech.get("runtimes") or {}
    w("| stage | wall time (s) |\n|---|---|")
    for k, v in rt.items():
        w(f"| {k} | {v:.1f} |")
    if not rt:
        w(f"| {PENDING} | |")
    w("")

    # ------------------------------------------------------------------ comparison
    w("## COMSOL vs analytic model\n")
    w("Full table: `comsol/comparison.csv`. The headline quantities:\n")
    head = ["zn_um", "eps_per_kappa_um", "eps_wrist_pct", "eps_elbow_pct", "eps_walking_pct", "art_wrist_pct",
            "art_elbow_pct", "art_walking_pct", "GF_ch_0p3", "GF_c", "GF_tot_0p3", "dVT_sweat_mV", "FS_pct",
            "R_phys_low_pct", "R_phys_high_pct", "exact_false_walking_at30", "exact_false_walking_at50",
            "exact_false_elbow_at30", "exact_false_wrist_at30", "xtalk_floor_pct_FS",
            "dyn_baseline.C_twin_filt.wrist.rms", "dyn_thin.C_twin_filt.wrist.rms", "dyn_island.C_twin_filt.wrist.rms",
            "check_debye_100mM_nm", "check_symmetric_stack_strain"]
    by = {r["quantity"]: r for r in rows}
    w("| quantity | COMSOL | analytic | diff (%) | note |\n|---|---|---|---|---|")
    for h in head:
        r = by.get(h)
        w(f"| {h} | {fmt(r['comsol'], 5) if r else PENDING} | {fmt(r['python'], 5) if r else ''} | "
          f"{r['percent_difference'] if r else ''} | {r['note'] if r else ''} |")
    for n, r in by.items():
        if n.startswith("mitigation_pct_FS") and n.endswith("eps_wrist_pct"):
            w(f"| {n} | {fmt(r['comsol'], 5)} | {fmt(r['python'], 5)} | {r['percent_difference']} | {r['note']} |")
    w("")
    flagged = [r for r in rows if r["note"].startswith(">")]
    w("## Differences larger than 5 %\n")
    if not rows:
        w(PENDING + "\n")
    elif not flagged:
        w("None.\n")
    else:
        w("COMSOL was not tuned to match. Physical reasons:\n")
        done = set()
        for r in flagged:
            key = next((k for k in EXPLAIN if k in r["quantity"] and EXPLAIN[k]), None)
            if key is None and ("Rigid island" in r["quantity"] or r["quantity"].startswith("dyn_island")):
                key = "Rigid island"
            txt = EXPLAIN.get(key) if key else None
            if key in done:
                w(f"- `{r['quantity']}`: {r['percent_difference']} % (same cause as above).")
                continue
            done.add(key)
            w(f"- `{r['quantity']}`: {r['percent_difference']} %. "
              + (txt or "Not explained automatically; the physical reason is discussed in the text."))
        w("")
    open(os.path.join(HERE, "COMSOL_METHODS.md"), "w").write("\n".join(L))
    print("wrote comsol/COMSOL_METHODS.md")


if __name__ == "__main__":
    main()
